# ---------------------------------------------------------------- helpers
def now() -> float: return time.monotonic()

def pct(xs, p):
    if not xs: return None
    xs = sorted(xs); k = max(0, min(len(xs) - 1, int(round(p / 100 * (len(xs) - 1)))))
    return round(xs[k], 3)

def summarize(xs):
    return {"n": len(xs), "p50": pct(xs, 50), "p90": pct(xs, 90), "p99": pct(xs, 99),
            "max": round(max(xs), 3) if xs else None, "mean": round(statistics.mean(xs), 3) if xs else None}

def save(test, data):
    OUT.mkdir(parents=True, exist_ok=True)
    data = {"test": test, "target": TARGET, "run": RUN, "at": datetime.now().isoformat(timespec="seconds"), **data}
    (OUT / f"{test}.json").write_text(json.dumps(data, indent=2))
    print(json.dumps(data, indent=2))

def kubectl(*args, timeout=900, check=True) -> str:
    r = subprocess.run(["kubectl", "-n", NS, *args], capture_output=True, text=True, timeout=timeout)
    if check and r.returncode != 0:
        raise RuntimeError(f"kubectl {' '.join(args)} failed: {r.stderr.strip()}")
    return r.stdout

def exec_in(pod, cmd: str, env: dict | None = None, timeout=900) -> str:
    prefix = " ".join(f"{k}='{v}'" for k, v in (env or {}).items())
    return kubectl("exec", pod, "-c", "sandbox", "--", "bash", "-c", f"{prefix} {cmd}".strip(), timeout=timeout)

def json_lines(s: str): return [json.loads(l) for l in s.splitlines() if l.strip().startswith("{")]

def s3_env():
    return {"AWS_ACCESS_KEY_ID": S3["S3_ACCESS_KEY"], "AWS_SECRET_ACCESS_KEY": S3["S3_SECRET_KEY"],
            "S3_ENDPOINT_URL": S3["S3_ENDPOINT"], "S3_BUCKET": S3["S3_BUCKET"]}

def pool_ready(pool) -> int:
    o = CO.get_namespaced_custom_object(GROUP, VER, NS, "sandboxwarmpools", pool)
    return int(o.get("status", {}).get("readyReplicas") or 0)

def pool_spec(pool) -> int:
    return int(CO.get_namespaced_custom_object(GROUP, VER, NS, "sandboxwarmpools", pool)["spec"].get("replicas") or 0)

def scale_pool(pool, n, wait=True, timeout=900):
    if n is None: n = pool_spec(pool)          # default: keep the pool at its configured size
    CO.patch_namespaced_custom_object(GROUP, VER, NS, "sandboxwarmpools", pool, {"spec": {"replicas": n}})
    if not wait: return
    t0 = now()
    while pool_ready(pool) < n:
        if now() - t0 > timeout: raise TimeoutError(f"pool {pool} not ready: {pool_ready(pool)}/{n}")
        time.sleep(2)


class ClaimWatcher:
    """One watch on all SandboxClaims in NS; records first time each claim is Ready."""
    def __init__(self):
        self.ready: dict[str, float] = {}; self.info: dict[str, dict] = {}
        self.cv = threading.Condition(); self._stop = False
        threading.Thread(target=self._run, daemon=True).start()

    def _run(self):
        rv = None
        while not self._stop:
            try:
                w = watch.Watch()
                kw = {"resource_version": rv} if rv else {}
                for ev in w.stream(CO.list_namespaced_custom_object, GROUP, VER, NS, "sandboxclaims",
                                   timeout_seconds=300, **kw):
                    o = ev["object"]; rv = o["metadata"].get("resourceVersion"); name = o["metadata"]["name"]
                    conds = o.get("status", {}).get("conditions") or []
                    if any(c.get("type") == "Ready" and c.get("status") == "True" for c in conds):
                        with self.cv:
                            if name not in self.ready:
                                self.ready[name] = now(); self.info[name] = o.get("status", {}).get("sandbox", {})
                                self.cv.notify_all()
            except Exception:  # 410 Gone / disconnect → relist
                rv = None; time.sleep(0.5)

    def wait(self, name, timeout) -> float | None:
        with self.cv:
            self.cv.wait_for(lambda: name in self.ready, timeout=timeout)
            return self.ready.get(name)


WATCHER: ClaimWatcher | None = None
def watcher() -> ClaimWatcher:
    global WATCHER
    if WATCHER is None: WATCHER = ClaimWatcher(); time.sleep(1)
    return WATCHER

def create_claim(pool, prefix="b") -> tuple[str, float]:
    name = f"{prefix}-{uuid.uuid4().hex[:10]}"
    body = {"apiVersion": f"{GROUP}/{VER}", "kind": "SandboxClaim", "metadata": {"name": name, "namespace": NS},
            "spec": {"warmPoolRef": {"name": pool}}}
    t0 = now(); CO.create_namespaced_custom_object(GROUP, VER, NS, "sandboxclaims", body)
    return name, t0

def delete_claim(name):
    try: CO.delete_namespaced_custom_object(GROUP, VER, NS, "sandboxclaims", name)
    except client.ApiException as e:
        if e.status != 404: raise

def claim_ready(pool, timeout=180, prefix="b"):
    """Create a claim and wait for Ready. Returns (name, seconds|None)."""
    name, t0 = create_claim(pool, prefix)
    t = watcher().wait(name, timeout)
    return name, (round(t - t0, 3) if t else None)

def pod_of(claim) -> str:
    sb = watcher().info.get(claim, {}).get("name")
    if not sb:
        sb = CO.get_namespaced_custom_object(GROUP, VER, NS, "sandboxclaims", claim)["status"]["sandbox"]["name"]
    try:
        CORE.read_namespaced_pod(sb, NS); return sb
    except client.ApiException:
        sel = CO.get_namespaced_custom_object("agents.x-k8s.io", "v1beta1", NS, "sandboxes", sb)["status"]["selector"]
        return CORE.list_namespaced_pod(NS, label_selector=sel).items[0].metadata.name

def api_probe_loop(samples: list, stop: threading.Event, every=1.0, pool=None, pool_min=None):
    """API-server health while under load: latency of GET /version and a 1-item LIST of sandboxes.
    Optionally tracks the minimum ready size of `pool` (into pool_min[0])."""
    while not stop.is_set():
        if pool is not None:
            try: pool_min[0] = min(pool_min[0], pool_ready(pool))
            except Exception: pass
        t0 = now()
        try:
            VERSION.get_code(); CO.list_namespaced_custom_object("agents.x-k8s.io", "v1beta1", NS, "sandboxes", limit=1)
            samples.append(now() - t0)
        except Exception:
            samples.append(30.0)
        stop.wait(every)


# ---------------------------------------------------------------- Day 1
def t_latency(a):
    """Warm path: sequential claims against a full pool. Also time to first exec."""
    scale_pool(a.pool, a.pool_size)
    claim_s, exec_s, fails = [], [], 0
    for i in range(a.n):
        while pool_ready(a.pool) < 1: time.sleep(0.5)   # keep it a warm-path measurement
        name, s = claim_ready(a.pool, timeout=60)
        if s is None: fails += 1; delete_claim(name); continue
        claim_s.append(s)
        if i < a.exec_samples:
            t0 = now(); exec_in(pod_of(name), "true"); exec_s.append(now() - t0)
        delete_claim(name)
    save("latency_warm", {"pool": a.pool, "claim_ready_s": summarize(claim_s),
                          "first_exec_via_kubectl_s": summarize(exec_s), "failures": fails,
                          "note": "first_exec includes kubectl exec overhead; srvm data path (gateway→sandboxd) will be faster"})

def t_cold(a):
    """Cold path: claims against a 0-replica pool (create pod from scratch, image already on node)."""
    lat, fails = [], 0
    for _ in range(a.n):
        name, s = claim_ready("cold", timeout=300)
        (lat.append(s) if s is not None else None); fails += s is None
        delete_claim(name)
    save("latency_cold", {"claim_ready_s": summarize(lat), "failures": fails,
                          "note": "image pre-pulled; excludes node provisioning (+30-90s on cloud) and image pull"})

def t_burst(a):
    res = {}
    if a.pool_size is None: a.pool_size = pool_spec(a.pool)
    for n in a.sizes:
        scale_pool(a.pool, a.pool_size)
        with cf.ThreadPoolExecutor(max_workers=min(n, 128)) as ex:
            out = list(ex.map(lambda _: claim_ready(a.pool, timeout=300, prefix="burst"), range(n)))
        lat = [s for _, s in out if s is not None]
        res[str(n)] = {"claim_ready_s": summarize(lat), "failures": n - len(lat), "pool_size": a.pool_size,
                       "beyond_pool": max(0, n - a.pool_size)}
        for name, _ in out: delete_claim(name)
        time.sleep(a.cooldown)
    save("burst", {"pool": a.pool, "results": res})

def t_ramp(a):
    """Sustained claim rate steps. Each claim held `hold` s then deleted. Finds the per-cell L1 ceiling."""
    if a.pool_size is None: a.pool_size = pool_spec(a.pool)
    scale_pool(a.pool, a.pool_size)
    steps = []
    for rate in a.rates:
        lat, fails, pool_min, probes = [], [0], [10**9], []
        stop = threading.Event(); threading.Thread(target=api_probe_loop, args=(probes, stop, 1.0, a.pool, pool_min), daemon=True).start()
        lock = threading.Lock()

        def one():
            name, s = claim_ready(a.pool, timeout=a.timeout, prefix=f"r{rate}")
            with lock:
                if s is None: fails[0] += 1
                else: lat.append(s)
            time.sleep(a.hold); delete_claim(name)

        with cf.ThreadPoolExecutor(max_workers=max(64, rate * (a.hold + 15))) as ex:
            t_start = now(); futs = []; i = 0
            while (el := now() - t_start) < a.duration:
                due = int(el * rate)
                while i < due: futs.append(ex.submit(one)); i += 1
                time.sleep(0.02)
            cf.wait(futs)
        stop.set()
        warm_frac = round(sum(1 for x in lat if x < 2.0) / max(1, i), 3)
        step = {"rate_per_s": rate, "issued": i, "claim_ready_s": summarize(lat), "failures": fails[0],
                "frac_ready_under_2s": warm_frac, "pool_ready_min": pool_min[0],
                "api_probe_s": summarize(probes)}
        steps.append(step); print(json.dumps(step))
        healthy = (step["claim_ready_s"]["p99"] or 99) < a.p99_limit and fails[0] == 0 and \
                  (step["api_probe_s"]["p99"] or 99) < 1.0
        if not healthy and a.stop_on_breach:
            print(f"ceiling breached at {rate}/s; stopping ramp"); break
        time.sleep(a.cooldown)
        scale_pool(a.pool, a.pool_size, timeout=1800)
    ok = [s["rate_per_s"] for s in steps if (s["claim_ready_s"]["p99"] or 99) < a.p99_limit
          and s["failures"] == 0 and (s["api_probe_s"]["p99"] or 99) < 1.0]
    save("ramp", {"pool": a.pool, "hold_s": a.hold, "duration_s": a.duration, "steps": steps,
                  "max_healthy_rate_per_s": max(ok) if ok else 0,
                  "healthy_def": f"claim p99 < {a.p99_limit}s, 0 failures, API probe p99 < 1s"})

def t_density(a):
    """Scale the 'tiny' pool up in steps until it stops getting Ready; per-node packing under gVisor."""
    nodes = CORE.list_node(label_selector="srvm.io/pool=sandbox").items
    results, last_ok = [], 0
    for n in range(a.step, a.max + 1, a.step):
        t0 = now()
        try:
            scale_pool("tiny", n, timeout=a.timeout); results.append({"replicas": n, "ready_s": round(now() - t0, 1)}); last_ok = n
        except TimeoutError:
            results.append({"replicas": n, "ready": pool_ready("tiny"), "timeout": True}); break
    pending = len([p for p in CORE.list_namespaced_pod(NS, label_selector="srvm.io/template=tiny").items
                   if p.status.phase == "Pending"])
    alloc = [{"node": nd.metadata.name, "allocatable": nd.status.allocatable} for nd in nodes]
    scale_pool("tiny", 0, wait=False)
    save("density", {"sandbox_nodes": len(nodes), "max_ready": last_ok, "per_node": round(last_ok / max(1, len(nodes)), 1),
                     "pending_at_stop": pending, "steps": results, "nodes": alloc,
                     "note": "tiny = 100m/128Mi. Limits hit: CPU/mem requests, maxPods (110), or runsc overhead"})


# ---------------------------------------------------------------- Day 2
def t_resume(a):
    """Persistent workspace: gen → snapshot (pause) → new warm pod → hydrate (resume) → verify."""
    res = []
    for mb in a.sizes:
        sid = f"ws-{mb}mb-{uuid.uuid4().hex[:6]}"
        c1, _ = claim_ready(a.pool, prefix="ws"); p1 = pod_of(c1)
        gen = json_lines(exec_in(p1, f"snap.sh gen {mb}", timeout=1800))[-1]
        d1 = json_lines(exec_in(p1, "snap.sh digest"))[-1]
        snap = json_lines(exec_in(p1, f"snap.sh snapshot {sid}", s3_env(), timeout=1800))[-1]
        delete_claim(c1)                                   # pod released = "paused"
        t0 = now()
        c2, claim_s = claim_ready(a.pool, prefix="ws"); p2 = pod_of(c2)
        hyd = json_lines(exec_in(p2, f"snap.sh hydrate {sid}", s3_env(), timeout=1800))[-1]
        t_first = now(); exec_in(p2, "ls /workspace/ws >/dev/null"); resume_total = round(now() - t0, 2)
        d2 = json_lines(exec_in(p2, "snap.sh digest"))[-1]
        delete_claim(c2)
        r = {"size_mb": mb, "gen": gen, "snapshot": snap, "resume_claim_s": claim_s, "hydrate": hyd,
             "resume_end_to_end_s": resume_total, "intact": d1 == d2, "digest": d1}
        res.append(r); print(json.dumps(r))
    save("resume", {"pool": a.pool, "results": res,
                    "note": "prototype: tar+zstd+64MB chunks, s5cmd 32 workers. Production = content-addressed incremental chunks"})

def t_compat(a):
    out = {}
    for pool in ("open", "runc"):
        c, _ = claim_ready(pool, prefix="compat"); p = pod_of(c)
        out[pool] = json_lines(exec_in(p, "compat.sh", timeout=3600)); delete_claim(c)
    rows = []
    runc = {r["step"]: r for r in out["runc"]}
    for r in out["open"]:
        b = runc.get(r["step"], {})
        rows.append({"step": r["step"], "gvisor_ok": r["ok"], "runc_ok": b.get("ok"), "gvisor_s": r["secs"],
                     "runc_s": b.get("secs"), "slowdown_x": round(r["secs"] / b["secs"], 2) if b.get("secs") else None})
    save("compat", {"rows": rows, "raw": out})

def t_escape(a):
    peer_c, _ = claim_ready("locked", prefix="peer"); peer = pod_of(peer_c)
    kubectl("exec", peer, "-c", "sandbox", "--", "bash", "-c",
            "nohup python3 -m http.server 8000 >/dev/null 2>&1 &")
    peer_ip = CORE.read_namespaced_pod(peer, NS).status.pod_ip
    time.sleep(2)
    listening = subprocess.run(["kubectl", "-n", NS, "exec", peer, "-c", "sandbox", "--", "curl", "-s", "-m", "3",
                                "-o", "/dev/null", "-w", "%{http_code}", "http://127.0.0.1:8000/"],
                               capture_output=True, text=True).stdout.strip() == "200"
    att_c, _ = claim_ready("locked", prefix="attacker"); att = pod_of(att_c)
    rows = json_lines(exec_in(att, f"escape.sh {peer_ip} {S3['S3_ENDPOINT']}"))
    rows.append({"check": "peer_server_listening_control", "pass": listening,
                 "detail": "peer http.server answers on localhost (proves peer_sandbox_blocked is real)"})
    delete_claim(peer_c); delete_claim(att_c)
    save("escape", {"all_pass": all(r["pass"] for r in rows), "checks": rows,
                    "note": "metadata checks are only meaningful on a cloud cluster" if TARGET == "kind" else ""})


# ---------------------------------------------------------------- report
def t_report(a):
    d = {p.stem: json.loads(p.read_text()) for p in sorted(OUT.glob("*.json"))}
    L = [f"# Bake-off results ({RUN}, target={TARGET})", ""]
    if TARGET == "kind":
        L += ["> **kind run:** functional results (compat, escape, resume correctness) are valid; latency, ceiling",
              "> and density numbers reflect a laptop VM, not a cell. Re-run on GKE for capacity numbers.", ""]
    crit = []
    def row(name, val, target, ok): crit.append(f"| {name} | {val} | {target} | {'✅' if ok else '❌'} |")
    if w := d.get("latency_warm"): p = w["claim_ready_s"]["p99"]; row("Warm claim p99", f"{p}s", "< 1s", p is not None and p < 1)
    if c := d.get("latency_cold"): p = c["claim_ready_s"]["p99"]; row("Cold claim p99", f"{p}s", "< 15s", p is not None and p < 15)
    if r := d.get("ramp"): m = r["max_healthy_rate_per_s"]; row("Sustained claim ceiling", f"{m}/s", "≥ 20/s", m >= 20)
    if r := d.get("resume"):
        big = max(r["results"], key=lambda x: x["size_mb"])
        row(f"Resume {big['size_mb']} MB end-to-end", f"{big['resume_end_to_end_s']}s", "< 10s", big["resume_end_to_end_s"] < 10)
        row("Workspace intact after resume", all(x["intact"] for x in r["results"]), "true", all(x["intact"] for x in r["results"]))
    if c := d.get("compat"): okc = all(x["gvisor_ok"] for x in c["rows"]); row("gVisor compat", f"{sum(x['gvisor_ok'] for x in c['rows'])}/{len(c['rows'])}", "all", okc)
    if e := d.get("escape"): row("Escape suite", f"{sum(x['pass'] for x in e['checks'])}/{len(e['checks'])}", "100%", e["all_pass"])
    L += ["## Exit criteria", "", "| Check | Measured | Target | |", "|---|---|---|---|", *crit, ""]
    for k, v in d.items():
        L += [f"## {k}", "", "```json", json.dumps({x: y for x, y in v.items() if x not in ("raw",)}, indent=2)[:6000], "```", ""]
    (OUT / "summary.md").write_text("\n".join(L)); print("\n".join(L[:40])); print(f"\nwritten: {OUT/'summary.md'}")


# ---------------------------------------------------------------- CLI
def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sp = ap.add_subparsers(dest="cmd", required=True)
    pool_size = int(os.environ["POOL_SIZE"]) if os.environ.get("POOL_SIZE") else None  # None = keep current
    def add(name, fn, **kw):
        p = sp.add_parser(name); p.set_defaults(fn=fn)
        p.add_argument("--pool", default="locked"); p.add_argument("--pool-size", type=int, default=pool_size)
        for k, (typ, dflt) in kw.items():
            if typ == "ints": p.add_argument(f"--{k}", type=lambda s: [int(x) for x in s.split(",")], default=dflt)
            elif typ == "flag": p.add_argument(f"--{k}", action="store_true", default=dflt)
            else: p.add_argument(f"--{k}", type=typ, default=dflt)
        return p
    add("latency", t_latency, n=(int, 200), **{"exec-samples": (int, 20)})
    add("cold", t_cold, n=(int, 30))
    add("burst", t_burst, sizes=("ints", [50, 100, 200]), cooldown=(int, 30))
    add("ramp", t_ramp, rates=("ints", [10, 20, 30, 40, 60]), duration=(int, 300), hold=(int, 10),
        timeout=(int, 120), cooldown=(int, 60), **{"p99-limit": (float, 5.0), "stop-on-breach": ("flag", True)})
    add("density", t_density, step=(int, 25), max=(int, 400), timeout=(int, 300))
    add("resume", t_resume, sizes=("ints", [100, 500, 1024, 2048])).set_defaults(pool="ws")
    add("compat", t_compat); add("escape", t_escape); add("report", t_report)
    a = ap.parse_args()
    for k in list(vars(a)): setattr(a, k.replace("-", "_"), getattr(a, k))
    print(f"run={RUN} target={TARGET} ns={NS} → {OUT}")
    a.fn(a)

if __name__ == "__main__":
    main()
